// =====================================================
// DATE NAMES
// =====================================================
//
// Filipino and Cebuano both use Spanish-derived month
// names that are effectively identical, but their weekday
// names differ slightly, so each gets its own array.

export const MONTHS_LONG = {
  en: ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'],
  fil: ['Enero', 'Pebrero', 'Marso', 'Abril', 'Mayo', 'Hunyo', 'Hulyo', 'Agosto', 'Septyembre', 'Oktubre', 'Nobyembre', 'Disyembre'],
  ceb: ['Enero', 'Pebrero', 'Marso', 'Abril', 'Mayo', 'Hunyo', 'Hulyo', 'Agosto', 'Septyembre', 'Oktubre', 'Nobyembre', 'Disyembre'],
};

export const MONTHS_SHORT = {
  en: ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'],
  fil: ['Ene', 'Peb', 'Mar', 'Abr', 'May', 'Hun', 'Hul', 'Ago', 'Sep', 'Okt', 'Nob', 'Dis'],
  ceb: ['Ene', 'Peb', 'Mar', 'Abr', 'May', 'Hun', 'Hul', 'Ago', 'Sep', 'Okt', 'Nob', 'Dis'],
};

// Sunday-first, for full weekday names.
export const WEEKDAYS_LONG = {
  en: ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'],
  fil: ['Linggo', 'Lunes', 'Martes', 'Miyerkules', 'Huwebes', 'Biyernes', 'Sabado'],
  ceb: ['Domingo', 'Lunes', 'Martes', 'Miyerkules', 'Huwebes', 'Biyernes', 'Sabado'],
};

// Monday-first, matching the calendar grid's column order.
export const WEEKDAYS_SHORT_MON_FIRST = {
  en: ['Mo', 'Tu', 'We', 'Th', 'Fr', 'Sa', 'Su'],
  fil: ['Lun', 'Mar', 'Miy', 'Huw', 'Biy', 'Sab', 'Lin'],
  ceb: ['Lun', 'Mar', 'Miy', 'Huw', 'Biy', 'Sab', 'Dom'],
};

export function formatLongDate(date, langCode = 'en') {
  const weekdays = WEEKDAYS_LONG[langCode] || WEEKDAYS_LONG.en;
  const months = MONTHS_LONG[langCode] || MONTHS_LONG.en;

  return `${weekdays[date.getDay()]}, ${months[date.getMonth()]} ${date.getDate()}, ${date.getFullYear()}`;
}

export function formatMonthYear(date, langCode = 'en') {
  const months = MONTHS_LONG[langCode] || MONTHS_LONG.en;
  return `${months[date.getMonth()]} ${date.getFullYear()}`;
}

export function formatShortDateLocalized(date, langCode = 'en') {
  const months = MONTHS_SHORT[langCode] || MONTHS_SHORT.en;
  return `${months[date.getMonth()]} ${date.getDate()}`;
}

